/* WE ARE GOING TO CREATE THE NEW DATABASE WITH NAME AMEZON*/

CREATE DATABASE AMEZON

USE AMEZON

 DDL_OPERATIONS:

 /* CRATE*/
CREATE TABLE EMPLOYEE_DETAILS  (EMPID INT, EMPNAME CHAR(10) , EMP_AGE TINYINT , EMPSALARY MONEY)

/* ALTER ,1. ALTER IS USED TO CHANGE THE DATA TYPE OF THE COLUMN */
ALTER TABLE EMPLOYEE_DETAILS ALTER COLUMN EMP_AGE INT

/* 2, USING ALTER WE CAN CREATE A NEW COLUMN*/
ALTER TABLE EMPLOYEE_DETAILS ADD EMP_LOC VARCHAR(10)

/* 3, USING ALTER WE CAN REMOVE THE COLUMN FROM THE TABLE*/
ALTER TABLE EMPLOYEE_DETAILS DROP COLUMN EMP_AGE 

/* SP_RENAME , FUNCTION IS USED TO CHANGE THE COLUMN NAME */

SP_RENAME 'EMPLOYEE_DETAILS.EMP_LOC' , 'ADDRESS'

 /*TRUNCATE , WE CAN REMOVE ALL THE ROWS INTHE TABLE BUT THE TABLE WILL ALIVE */
  TRUNCATE TABLE EMPLOYEE_DETAILS 

/* DROP , IT IS GOING TO DELETE TABLE FROM THE DATABASE*/
DROP TABLE EMPLOYEE_DETAILS

/* TO SHOW THE TABLE AND THE DATA INSIDE THE TABLE FOLLOW BELOW QUERY*/

 SELECT *FROM EMPLOYEE_DETAILS

